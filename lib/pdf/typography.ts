// Типографика текстов PDF.
//
// В колоде много узких колонок, и автоматический перенос react-pdf регулярно
// оставлял то висячий предлог в конце строки («…конкурентов и / ссылок»), то
// одинокое слово на последней строке («…по цене 1 специалиста в / штате»).
// Правится это не вёрсткой, а неразрывными пробелами: здесь они расставляются
// один раз для всех текстов слайдов — функция вызывается из `clean()`
// (lib/pdf/theme.ts), через который проходит каждая строка колоды.
//
// 🛑 Неразрывный пробел склеивает слова в один «токен» для переносчика: группа,
// которая шире колонки, вылезет за её край. Поэтому правила консервативные —
// склеиваем только короткие сочетания (пороги ниже выверены по самой узкой
// колонке колоды: описания сервисов на слайде инструментария, ~35 знаков).

const NBSP = " ";

/**
 * Предлоги, союзы и частицы, которые нельзя оставлять в конце строки:
 * классическое правило русской типографики. Список закрытый — трёхбуквенное
 * слово вроде «все» не предлог, и приклеивать его к следующему не надо.
 */
const GLUE_WORDS = new Set([
  // предлоги
  "в", "во", "к", "ко", "с", "со", "о", "об", "обо", "у", "из", "изо", "от",
  "ото", "до", "за", "на", "над", "надо", "под", "подо", "при", "про", "по",
  "для", "без", "безо", "перед", "через", "между", "среди",
  // союзы и частицы
  "и", "а", "но", "да", "или", "либо", "ни", "не", "же", "ли", "бы", "то",
  "как", "что", "чтобы", "если", "хотя",
  // латиница (в текстах попадаются английские названия)
  "a", "an", "the", "of", "in", "on", "for", "to", "and",
]);

/** Число: «46», «3,5», «80+», «95%». Приклеивается к следующему слову. */
const NUMBER_RE = /^\d+(?:[.,]\d+)?[+%]?$/;

/**
 * Одиночный знак-связка: тире или «=». Строку начинать им нельзя, поэтому
 * приклеиваем к предыдущему слову. Сверяется с «сырым» токеном: `core()`
 * вычищает всё, кроме букв и цифр, и от такого знака ничего бы не осталось.
 */
const DASH_RE = /^[—–=]$/;

const CYRILLIC = /[\u0400-\u04FF]/;
const LATIN = /[A-Za-z]/;

/**
 * 🛑 Неразрывный пробел на границе алфавитов рвётся с лишним дефисом.
 * `scriptItemizer` в @react-pdf/textkit режет строку на runs по юникод-скрипту
 * ДО переноса слов, а неразрывный пробел пробела не образует — «в<NBSP>AI-ответах»
 * становится одним словом из двух runs, между ними встаёт penalty-узел, и при
 * переносе react-pdf дописывает дефис: «в -» / «AI-ответах» (те же грабли, что
 * описаны у колбэка переносов в theme.ts, только колбэк тут не поможет —
 * penalty ставит сам textkit).
 *
 * Поэтому кириллицу с латиницей не склеиваем: перенос в этом месте разрешён,
 * зато без мусорного дефиса.
 */
function crossesScripts(a: string, b: string): boolean {
  const end = [...a].reverse().find((ch) => CYRILLIC.test(ch) || LATIN.test(ch));
  const start = [...b].find((ch) => CYRILLIC.test(ch) || LATIN.test(ch));
  if (!end || !start) return false;
  return CYRILLIC.test(end) !== CYRILLIC.test(start);
}

/**
 * Слово без разметки `**` / `==` и без окружающей пунктуации — то, что реально
 * видит читатель. По нему и решаем, короткое слово или нет.
 */
function core(token: string): string {
  return token
    .replace(/[*=]/g, "")
    .replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, "");
}

/** Длина видимой части токена (разметка `**`/`==` шириной не обладает). */
function visibleLength(token: string): number {
  return token.replace(/[*=]/g, "").length;
}

/**
 * Максимальная длина «слипшейся» пары слов на последней строке. 20 знаков даже
 * самым мелким кеглем колоды (4.9 pt) занимают ~50 pt — влезает в любую колонку.
 */
const WIDOW_PAIR_MAX = 20;
/** Одинокое слово длиннее этого переносить не жалко — строка не выглядит пустой. */
const WIDOW_WORD_MAX = 10;

/**
 * Расставить неразрывные пробелы:
 *   • после предлогов, союзов и частиц («и ссылок» уезжает на строку целиком);
 *   • после числа («46 инструментов», «3–5 человек», «30 000 $»);
 *   • перед тире («…бизнеса — это…» не начнёт строку с тире);
 *   • между двумя последними словами, если они короткие, — против висячей
 *     строки из одного слова.
 */
export function typography(str: string): string {
  const tokens = str.split(" ");
  if (tokens.length < 2) return str;

  // separators[i] — пробел между tokens[i] и tokens[i + 1].
  const separators: string[] = new Array(tokens.length - 1).fill(" ");

  for (let i = 0; i < tokens.length - 1; i++) {
    if (DASH_RE.test(tokens[i + 1])) {
      separators[i] = NBSP;
      continue;
    }
    const prev = core(tokens[i]).toLowerCase();
    if (crossesScripts(prev, core(tokens[i + 1]))) continue;
    if (GLUE_WORDS.has(prev) || NUMBER_RE.test(prev)) {
      separators[i] = NBSP;
    }
  }

  // Висячее слово: приклеиваем хвост к предпоследнему слову. Пунктуацию
  // («решение.») считаем частью слова — она и переносится вместе с ним.
  const last = tokens.length - 1;
  if (
    last >= 2 &&
    !crossesScripts(core(tokens[last - 1]), core(tokens[last])) &&
    visibleLength(tokens[last]) <= WIDOW_WORD_MAX &&
    visibleLength(tokens[last - 1]) + visibleLength(tokens[last]) <= WIDOW_PAIR_MAX
  ) {
    separators[last - 1] = NBSP;
  }

  return tokens.reduce(
    (acc, token, i) => (i === 0 ? token : acc + separators[i - 1] + token),
    "",
  );
}
