// Типографика текстов PDF: неразрывные пробелы (lib/pdf/typography.ts).
//
// Модуль чистый и без зависимостей — специально, чтобы его можно было проверить
// тестом, не поднимая react-pdf.

import { describe, expect, it } from "vitest";
import { typography } from "../lib/pdf/typography";

const NBSP = " ";

describe("typography", () => {
  it("приклеивает предлоги и союзы к следующему слову", () => {
    expect(typography("сервис для анализа конкурентов и ссылок")).toBe(
      `сервис для${NBSP}анализа конкурентов и${NBSP}ссылок`,
    );
  });

  it("не трогает короткие слова, которые не предлоги", () => {
    const src = "все направления функционируют одновременно";
    expect(typography(src)).toBe(src);
  });

  it("приклеивает число к следующему слову", () => {
    expect(typography("46 профессиональных инструментов и сервисов")).toBe(
      `46${NBSP}профессиональных инструментов и${NBSP}сервисов`,
    );
  });

  it("не оставляет тире и «=» в начале строки", () => {
    expect(typography("длинный цикл — это долго")).toContain(`цикл${NBSP}—`);
    expect(typography("работа на каждом этапе = больше заявок")).toContain(
      `этапе${NBSP}=`,
    );
  });

  it("склеивает два последних коротких слова — против висячей строки", () => {
    expect(typography("Опытных специалистов, работающих без опыта")).toBe(
      `Опытных специалистов, работающих без${NBSP}опыта`,
    );
  });

  it("не склеивает последние слова, если пара длинная", () => {
    const src = "Покупатель сначала внимательно изучает предложение";
    expect(typography(src)).toBe(src);
  });

  it("видит слово сквозь разметку **жирного** и ==хайлайта==", () => {
    expect(typography("Команду из 3–5 человек **по цене 1 специалиста**")).toBe(
      `Команду из${NBSP}3–5 человек **по${NBSP}цене 1${NBSP}специалиста**`,
    );
  });

  it("🛑 не склеивает кириллицу с латиницей: react-pdf дорисует дефис", () => {
    // «в<NBSP>AI-ответах» ломается на границе алфавитов и печатается как «в -».
    expect(typography("контент для использования в AI-ответах")).toBe(
      `контент для${NBSP}использования в AI-ответах`,
    );
    expect(typography("трафик из ChatGPT")).toBe("трафик из ChatGPT");
  });

  it("оставляет строку из одного слова как есть", () => {
    expect(typography("Смета")).toBe("Смета");
  });
});
